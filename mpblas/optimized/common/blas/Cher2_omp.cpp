// The reference Cher2 (mpblas/reference/Cher2.cpp, unchanged) under the name
// Cher2_reference_cpu, and Cher2_omp: column ranges of A in parallel, each
// computed by Cher2_columns (generated by misc/gen_blas_column_variants.py;
// unit increments only).

#define Cher2 Cher2_reference_cpu
#include "../../../reference/Cher2.cpp"
#undef Cher2

#include "Cher2_columns.h"

#include <algorithm>
#include "../Rblas_split_common.h"

namespace {
bool ls(const char *a, const char *b) { return Mlsame(a, b) != 0; }
} // namespace

bool Cher2_omp(const char *uplo, INTEGER const n, COMPLEX const alpha, COMPLEX *x, INTEGER const incx, COMPLEX *y, INTEGER const incy, COMPLEX *a, INTEGER const lda)
{
    using namespace mplapack_blas;
    if ((!ls(uplo, "U") && !ls(uplo, "L")) || n <= 0 || incx != 1 || incy != 1 || lda < std::max((INTEGER)1, n))
        return false;
    return blas_split(8.0 * n * n, n, [&](long p0, long p1) { Cher2_columns(uplo, n, alpha, x, incx, y, incy, a, lda, p0, p1); });
}
