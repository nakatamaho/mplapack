// The reference Csyrk (mpblas/reference/Csyrk.cpp, unchanged) under the name
// Csyrk_reference_cpu, and Csyrk_omp: column ranges of the output in parallel,
// each computed by Csyrk_columns (the reference code restricted to the range;
// generated by misc/gen_blas_column_variants.py).

#define Csyrk Csyrk_reference_cpu
#include "../../../reference/Csyrk.cpp"
#undef Csyrk

#include "Csyrk_columns.h"

#include <algorithm>
#include "../Rblas_split_common.h"
#include "../Rblas_cpu_common.h"
#if defined(MPLAPACK_BUILD_WITH_DD) || defined(MPLAPACK_BUILD_WITH_TD) || defined(MPLAPACK_BUILD_WITH_QD)
#include "../Cblas_simd_common.h"
#endif

namespace {
bool ls(const char *a, const char *b) { return Mlsame(a, b) != 0; }
} // namespace

bool Csyrk_omp(const char *uplo, const char *trans, INTEGER const n, INTEGER const k, COMPLEX const alpha, COMPLEX *a, INTEGER const lda, COMPLEX const beta, COMPLEX *c, INTEGER const ldc)
{
    using namespace mplapack_blas;
    const bool notr = ls(trans, "N");
    if ((!ls(uplo, "U") && !ls(uplo, "L")) || (!notr && !ls(trans, "T")) || n <= 0 || k < 0 || lda < std::max((INTEGER)1, notr ? n : k) || ldc < std::max((INTEGER)1, n))
        return false;
    // the small-block engine where it is faster (../Rblas_block_common.h)
    if (k > 0 && !(alpha == COMPLEX(0.0, 0.0)) && blk_syrk<blas_thread_context>(ls(uplo, "U"), !notr, n, k, alpha, a, lda, beta, c, ldc))
        return true;
#ifdef MPLAPACK_CBLAS_SIMD_AVAILABLE
    if (notr ? csyrk_simd<COMPLEX>(ls(uplo, "U"), n, k, alpha, a, lda, beta, c, ldc) : csyrk_t_simd<COMPLEX>(ls(uplo, "U"), n, k, alpha, a, lda, beta, c, ldc))
        return true;
#endif
    return blas_split(2.0 * n * n * k, n, [&](long p0, long p1) { Csyrk_columns(uplo, trans, n, k, alpha, a, lda, beta, c, ldc, p0, p1); });
}
