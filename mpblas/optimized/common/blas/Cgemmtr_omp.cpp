// The reference Cgemmtr (mpblas/reference/Cgemmtr.cpp, unchanged) under the name
// Cgemmtr_reference_cpu, and Cgemmtr_omp: column ranges of the output in parallel,
// each computed by Cgemmtr_columns (the reference code restricted to the range;
// generated by misc/gen_blas_column_variants.py).

#define Cgemmtr Cgemmtr_reference_cpu
#include "../../../reference/Cgemmtr.cpp"
#undef Cgemmtr

#include "Cgemmtr_columns.h"

#include <algorithm>
#include "../Rblas_split_common.h"

namespace {
bool ls(const char *a, const char *b) { return Mlsame(a, b) != 0; }
} // namespace

bool Cgemmtr_omp(const char *uplo, const char *transa, const char *transb, INTEGER const n, INTEGER const k, COMPLEX const alpha, COMPLEX *a, INTEGER const lda, COMPLEX *b, INTEGER const ldb, COMPLEX const beta, COMPLEX *c, INTEGER const ldc)
{
    using namespace mplapack_blas;
    const bool nota = ls(transa, "N"), notb = ls(transb, "N");
    if ((!ls(uplo, "U") && !ls(uplo, "L")) || (!nota && !ls(transa, "T") && !ls(transa, "C")) || (!notb && !ls(transb, "T") && !ls(transb, "C")) || n <= 0 || k < 0)
        return false;
    if (lda < std::max((INTEGER)1, nota ? n : k) || ldb < std::max((INTEGER)1, notb ? k : n) || ldc < std::max((INTEGER)1, n))
        return false;
    return blas_split(2.0 * n * n * k, n, [&](long p0, long p1) { Cgemmtr_columns(uplo, transa, transb, n, k, alpha, a, lda, b, ldb, beta, c, ldc, p0, p1); });
}
