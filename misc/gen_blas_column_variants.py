#!/usr/bin/env python3
"""Generate the column-range variants of reference BLAS routines.

For each routine below, every iteration of the loops
"for (j = 1; j <= n; j = j + 1)" of mpblas/reference/<R>.cpp touches only
column j of the output and carries no state to the next iteration.  The
variant <R>_columns(..., j0, j1) is the reference function with these loops
restricted to the columns j0 < j <= j1 (1-based j), so that disjoint column
ranges can run in parallel with the reference result bit for bit
(mpblas/optimized/common/blas/<R>_omp.cpp).  The reference sources are not
modified; rerun this script when they change.

usage: misc/gen_blas_column_variants.py   (from the top source directory)
"""
import re
import sys

ROUTINES = ["Rgemmtr", "Csyrk", "Cherk", "Csyr2k", "Cher2k", "Cgemmtr", "Cher", "Cher2"]
# In these, the loops of the non-unit-increment branches carry the vector
# indices from one column to the next: their variants are valid only for
# unit increments, and the callers use them only then.
UNIT_INCREMENT_ONLY = ["Cher", "Cher2"]
LOOP = "for (j = 1; j <= n; j = j + 1)"
HEADER = """// Generated by misc/gen_blas_column_variants.py from
// mpblas/reference/%s.cpp; do not edit.
//
// %s_columns: %s restricted to the columns j0 < j <= j1 (1-based j) of the
// output; the other columns are left untouched.

"""


def main():
    for r in ROUTINES:
        src = open("mpblas/reference/%s.cpp" % r).read()
        m = re.search(r"^void %s\((.*?)\) \{\n" % r, src, re.M)
        if not m:
            sys.exit("%s: function not found" % r)
        end = src.index("\n}\n", m.end())
        body = src[m.end():end + 3]
        if re.search(r"\bj = ", body.replace(LOOP, "").replace("INTEGER j = 0;", "")):
            sys.exit("%s: j is assigned outside the column loops" % r)
        count = body.count(LOOP)
        if count == 0:
            sys.exit("%s: no column loop" % r)
        body = body.replace(LOOP, "for (j = mplapack_j0 + 1; j <= mplapack_j1; j = j + 1)")
        sig = m.group(1) + ", INTEGER const mplapack_j0, INTEGER const mplapack_j1"
        out = HEADER % (r, r, r)
        if r in UNIT_INCREMENT_ONLY:
            out += "// Valid only for unit increments (the other branch carries indices).\n\n"
        out += "void %s_columns(%s) {\n" % (r, sig) + body
        open("mpblas/optimized/common/blas/%s_columns.h" % r, "w").write(out)
        print("wrote mpblas/optimized/common/blas/%s_columns.h (%d loops)" % (r, count))


if __name__ == "__main__":
    main()
