#!/usr/bin/env python3
"""Generate device (and host) templates of reference BLAS routines.

mpblas/optimized/common/blas_dev/<R>_dev.h holds the text of
mpblas/reference/<R>.cpp as
    template <class REAL, class COMPLEX> MPLAPACK_DEV_HD void <R>_dev(...)
in namespace mplapack_blas_dev, with Mlsame/Mxerbla mapped to the device
versions of ../Rblas_dev_base.h and INTEGER to mplapackint.  Instantiated
with the device types of Rblas_dev_types.h (dd/td/qd) or
mpfr/cuda/Cblas_mpfr_dev_types.h (MPFR), it performs the operations of the
reference routine, so GPU threads can compute independent parts of the
output with the reference results bit for bit (../Cblas_cuda_common.cuh).
For the routines of gen_blas_column_variants.py, <R>_columns_dev is the same
for the column-range variant.  The reference sources are not modified; rerun
this script when they change.

usage: misc/gen_blas_device_reference.py   (from the top source directory)
"""
import re
import sys

PLAIN = ["Cgemm", "Csymm", "Chemm", "Ctrmm", "Ctrsm", "Cgemv", "Cgeru", "Cgerc",
         "Caxpy", "Ccopy", "Cswap", "Cscal", "CRscal", "CRrot"]
COLUMNS = ["Rgemmtr", "Csyrk", "Cherk", "Csyr2k", "Cher2k", "Cgemmtr", "Cher", "Cher2"]
LOOP = "for (j = 1; j <= n; j = j + 1)"
OUT = "mpblas/optimized/common/blas_dev"


def function(r):
    src = open("mpblas/reference/%s.cpp" % r).read()
    m = re.search(r"^void %s\((.*?)\) \{\n" % r, src, re.M)
    if not m:
        sys.exit("%s: function not found" % r)
    end = src.index("\n}\n", m.end())
    return m.group(1), src[m.end():end + 3]


def device(sig, body):
    text = sig + ") {\n" + body
    text = re.sub(r"\bMlsame\(", "lsame(", text)
    text = re.sub(r"\bMxerbla\(", "xerbla(", text)
    text = re.sub(r"\bINTEGER\b", "mplapackint", text)
    for f in ("Rlamch", "castREAL", "castINTEGER", "sqrt", "pow"):
        if re.search(r"\b%s\(" % f, text):
            sys.exit("unsupported call %s" % f)
    return text


def main():
    names = []
    for r in PLAIN + COLUMNS:
        sig, body = function(r)
        name = r + "_dev"
        if r in COLUMNS:
            body = body.replace(LOOP, "for (j = mplapack_j0 + 1; j <= mplapack_j1; j = j + 1)")
            sig += ", INTEGER const mplapack_j0, INTEGER const mplapack_j1"
            name = r + "_columns_dev"
        out = ("// Generated by misc/gen_blas_device_reference.py from\n"
               "// mpblas/reference/%s.cpp; do not edit.\n\n"
               "namespace mplapack_blas_dev {\n\n"
               "template <class REAL, class COMPLEX> MPLAPACK_DEV_HD void %s(%s"
               "} // namespace mplapack_blas_dev\n") % (r, name, device(sig, body))
        open("%s/%s.h" % (OUT, name), "w").write(out)
        names.append(name)
    inc = "".join('#include "%s.h"\n' % n for n in names)
    # the range variants of misc/gen_blas_l2_ranges.py
    inc += '#include "l2_rows_dev.h"\n'
    open("%s/blas_dev.h" % OUT, "w").write(
        "// Generated by misc/gen_blas_device_reference.py; do not edit.\n"
        "// The device templates of the reference BLAS routines (see the script).\n\n"
        "#ifndef _MPLAPACK_BLAS_DEV_H_\n#define _MPLAPACK_BLAS_DEV_H_\n\n"
        "#include <mplapack_config.h>\n#include \"../Rblas_dev_base.h\"\n\n" + inc + "\n#endif\n")
    print("wrote %d device templates in %s" % (len(names), OUT))


if __name__ == "__main__":
    main()
