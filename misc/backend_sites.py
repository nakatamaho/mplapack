#!/usr/bin/env python3
"""List the places that name a model backend but not a new one.

    misc/backend_sites.py <model> <new> [--top DIR]

Run it while adding backend <new> modelled on <model> (for example
"dd td"): every line printed is a site that still has to be handled, or a
site where <new> deliberately does not follow <model>.  It reads the files
tracked by git and skips the per-backend directories and files of both
backends, generated example sources, release notes and logs.

Kinds of site (docs/adding-a-backend.md, sections 1 and 2.3-2.7):

  PP-OWN    #if/#elif that tests MPLAPACK_BUILD_WITH_<MODEL> alone, in a
            file with fewer such lines for <new>      -> add a block
  PP-GROUP  #if/#elif that tests <MODEL> together with other backends and
            not <new>                                 -> decide
  ENABLE    ENABLE_<MODEL>, enable_<model>, --enable-<model>,
            MPLAPACK_ENABLE_<MODEL>, in a file with fewer such lines
            for <new>                                 -> add <new>
  LIST      a line listing <model> among other backend names, without
            <new>                                     -> add <new>
  COPY      in a file that already mentions <new>, a line naming <model>
            whose renamed form (backend_rename.py) is not in the file
                                                      -> add the renamed line
  NAME      an identifier ending in _<model> (Mxerbla_dd, mpblas_dd.h.in)
            whose _<new> form does not occur in the file -> add it
  PLOT      a benchmark plot that draws <model> but not <new> -> decide

Lines of fable/*/lapack/patch-*.cpp are read without their diff marker
(removed lines are ignored), so a patch shows up like the source it makes.

Exit status is 0; the output is a to-do list, not a check.
"""

import argparse
import collections
import pathlib
import re
import subprocess
import sys

sys.dont_write_bytecode = True  # importing backend_rename must not leave misc/__pycache__
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from backend_rename import rename  # noqa: E402

SKIP_PREFIX = (
    "external/", "fable/3.9.1/", "doc/", "docs/", ".agents/",
    "examples/mplapack/0", "examples/mplapack/9",  # generated by examples/gen_all.sh
    "examples/mpblas/Makefile",
    "misc/backend_rename.py", "misc/backend_sites.py",  # their docs use dd as the example
)
SKIP_RE = re.compile(r"(/results/|^CHANGES|^ChangeLog|^MULTIPRECISION|\.md$|\.pdf$|\.log$|\.json$"
                     r"|(?<!CMakeLists)\.txt$)")


def backend_names(top):
    names = []
    for line in (top / "backends.txt").read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            names.append(line.split()[0])
    return names


def own_path(path, name):
    # Per-backend directory or file of <name>: .../dd/..., *_dd.*, *.dd.am, header_dd
    return bool(re.search(rf"(^|/){name}/|_{name}(\.|_|$)|\.{name}\.am$", path))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model")
    ap.add_argument("new")
    ap.add_argument("--top", default=pathlib.Path(__file__).resolve().parent.parent, type=pathlib.Path)
    args = ap.parse_args()
    top, m, n = args.top, args.model, args.new
    M, N = m.upper(), n.upper()
    others = [b for b in backend_names(top) if b not in (m, n)]

    files = subprocess.run(["git", "-C", str(top), "ls-files"], capture_output=True,
                           text=True, check=True).stdout.split()
    files = [f for f in files if not f.startswith(SKIP_PREFIX) and not SKIP_RE.search(f)
             and not own_path(f, m) and not own_path(f, n)]

    pp_m = re.compile(rf"\bMPLAPACK_BUILD_WITH_{M}\b")
    pp_n = re.compile(rf"\bMPLAPACK_BUILD_WITH_{N}\b")
    pp_any = re.compile(r"\bMPLAPACK_BUILD_WITH_[A-Z0-9]+\b")
    en_m = re.compile(rf"\bENABLE_{M}\b|\benable_{m}\b|--enable-{m}\b")
    en_n = re.compile(rf"\bENABLE_{N}\b|\benable_{n}\b|--enable-{n}\b")
    tok = r"(?<![A-Za-z0-9_.-]){}(?![A-Za-z0-9_-])"
    tok_m, tok_n = re.compile(tok.format(m)), re.compile(tok.format(n))
    tok_o = [re.compile(tok.format(o)) for o in others]
    name_m = re.compile(rf"\b([A-Za-z][A-Za-z0-9]*(?:_[A-Za-z0-9]+)*)_{m}\b")

    sites = collections.defaultdict(list)
    for f in files:
        try:
            lines = (top / f).read_text(errors="strict").splitlines()
        except (UnicodeDecodeError, IsADirectoryError, FileNotFoundError):
            continue
        if re.search(r"^fable/[^/]+/lapack/patch-", f):
            lines = ["" if l.startswith(("-", "@@")) else l[1:] for l in lines]
        if f.endswith(".plt.in"):
            if re.search(rf'\.{m}"', "\n".join(lines)) and not re.search(rf'\.{n}"', "\n".join(lines)):
                sites["PLOT"].append((f, 1, f"draws {m}, not {n}"))
            continue
        text = "\n".join(lines)
        own_m, own_n, en_lines, en_count_n = [], 0, [], 0
        for i, line in enumerate(lines, 1):
            s = line.strip()
            if s.startswith("#") and re.match(r"#\s*(if|elif|ifdef|ifndef)\b", s):
                tested = set(pp_any.findall(s))
                if pp_m.search(s) and len(tested) == 1:
                    own_m.append((i, s))
                elif pp_n.search(s) and len(tested) == 1:
                    own_n += 1
                elif pp_m.search(s) and not pp_n.search(s):
                    sites["PP-GROUP"].append((f, i, s))
                continue
            if en_m.search(s):
                en_lines.append((i, s))
            if en_n.search(s):
                en_count_n += 1
            if (tok_m.search(s) and not tok_n.search(s)
                    and sum(bool(o.search(s)) for o in tok_o) >= 2 and not en_m.search(s)):
                sites["LIST"].append((f, i, s))
        if len(own_m) > own_n:
            sites["PP-OWN"] += [(f, i, s) for i, s in own_m]
        if len(en_lines) > en_count_n:
            sites["ENABLE"] += [(f, i, s) for i, s in en_lines]
        # In a file that already handles <new>, a line naming <model> should
        # have its renamed counterpart: "mplapack_add_x(dd qd)" wants
        # "mplapack_add_x(td qd)".
        if tok_n.search(text) or pp_n.search(text):
            present = {l.strip() for l in lines}
            listed = {i for g, i, _ in sites["LIST"] if g == f}
            for i, line in enumerate(lines, 1):
                s = line.strip()
                if (i in listed or not tok_m.search(s) or tok_n.search(s)
                        or s.startswith("#") or en_m.search(s)):
                    continue
                if rename(s, m, n) not in present:
                    sites["COPY"].append((f, i, s))
        seen = set()
        for i, line in enumerate(lines, 1):
            for base in name_m.findall(line):
                if base in seen or base.startswith("MPLAPACK_BUILD_WITH"):
                    continue
                seen.add(base)
                if not re.search(rf"\b{re.escape(base)}_{n}\b", text):
                    sites["NAME"].append((f, i, f"{base}_{m}: {line.strip()}"))

    for kind in ("PP-OWN", "PP-GROUP", "ENABLE", "LIST", "COPY", "NAME", "PLOT"):
        entries = sites.get(kind, [])
        print(f"== {kind} ({len(entries)})")
        for f, i, s in entries:
            print(f"{f}:{i}: {s[:160]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
