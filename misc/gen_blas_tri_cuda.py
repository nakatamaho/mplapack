#!/usr/bin/env python3
"""Generate CUDA solve arithmetic from the unchanged reference TRSV bodies.

Storage/launch scheduling lives in Rtrisolve_jobs.h. Only independent products
and updates are parallel; the generated scalar expressions are not rewritten.
Also generate shadow dispatchers retaining the existing CPU _omp fallback.
"""
import re
from pathlib import Path
TOP = Path(__file__).resolve().parent.parent
def emit(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


out = (TOP / 'mpblas/reference/Rtrsv.cpp').read_text().split('*/', 1)[0] + '*/\n'
out += '// Generated by misc/gen_blas_tri_cuda.py; do not edit.\n'
out += 'namespace mplapack_trisolve __attribute__((visibility("hidden"))) {\n'
for prefix, ty in [('R', 'REAL'), ('C', 'COMPLEX')]:
    src = (TOP / f'mpblas/reference/{prefix}trsv.cpp').read_text()
    exprs = [
        ('divide', r'x\[j - 1\] = (x\[j - 1\] / a\[\(j - 1\) \+ \(j - 1\) \* lda\]);'),
        ('update', r'x\[i - 1\] = (x\[i - 1\] - temp \* a\[\(i - 1\) \+ \(j - 1\) \* lda\]);'),
        ('product', r'temp = temp - (a\[\(i - 1\) \+ \(j - 1\) \* lda\] \* x\[i - 1\]);'),
    ]
    out += f'template<class V> struct {prefix}arithmetic {{\n'
    for name, pattern in exprs:
        expr = re.search(pattern, src).group(1)
        expr = re.sub(r'a\[.*?\]', 'a', expr)
        expr = re.sub(r'x\[.*?\]', 'x', expr)
        out += f'    MPLAPACK_DEV_HD static V {name}(V x,V a,V temp=V(0.0)) {{ return {expr}; }}\n'
    out += '    MPLAPACK_DEV_HD static V conjugate(V a) { return ' + ('a' if prefix == 'R' else 'conj(a)') + '; }\n};\n'
out += '}\n'
emit(TOP / 'mpblas/optimized/common/blas_dev/tri_arithmetic.h', out)
for r in 'Rtrsv Rtbsv Rtpsv Ctrsv Ctbsv Ctpsv'.split():
    src = (TOP / f'mpblas/reference/{r}.cpp').read_text()
    sig = re.search(r'^void ' + r + r'\((.*?)\) \{', src, re.M).group(1)
    args = ', '.join(re.search(r'(\w+)$', a.strip()).group(1) for a in sig.split(','))
    text = '// Generated by misc/gen_blas_tri_cuda.py. CPU default unchanged.\n'
    text += '#include <mpblas.h>\n#include "../Rblas_cuda_entry_common.h"\n'
    text += f'bool {r}_omp({sig});\nvoid {r}_reference_cpu({sig});\n'
    text += f'void {r}({sig}) {{\n    if (!MPLAPACK_CUDA_ENTRY({r})({args}) && !{r}_omp({args}))\n        {r}_reference_cpu({args});\n}}\n'
    emit(TOP / f'mpblas/optimized/common/blas_cuda/{r}.cpp', text)
