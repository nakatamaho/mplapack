#!/usr/bin/env python3
"""Generate opt-in BLAS1 CUDA dispatchers without changing CPU fallbacks."""
import re
from pathlib import Path
TOP = Path(__file__).resolve().parent.parent
routines = 'Raxpy Rcopy Rdot Cdotc Cdotu Rasum RCasum Rnrm2 RCnrm2 iRamax iCamax'.split()
for r in routines:
    text = (TOP / f'mpblas/reference/{r}.cpp').read_text()
    m = re.search(r'^(void|REAL|COMPLEX|INTEGER)\s+' + r + r'\((.*?)\) \{', text, re.M)
    result, sig = m.groups()
    args = ', '.join(re.search(r'(\w+)$', a.strip()).group(1) for a in sig.split(','))
    s = '// Generated by misc/gen_blas1_cuda_dispatchers.py. Default: CPU unchanged.\n'
    s += '#include <mpblas.h>\n#include "../Rblas_cuda_entry_common.h"\n'
    if result == 'void':
        s += f'static void {r}_blas1_cpu({sig});\n#define {r} {r}_blas1_cpu\n'
        for b in ('DD', 'TD', 'QD', 'MPFR'):
            s += ('#if' if b == 'DD' else '#elif') + f' defined(MPLAPACK_BUILD_WITH_{b})\n#include "../../{b.lower()}/{r}.cpp"\n'
        s += f'#endif\n#undef {r}\nvoid {r}({sig}) {{\n'
        s += f'    if (!MPLAPACK_CUDA_ENTRY({r})({args})) {r}_blas1_cpu({args});\n}}\n'
    else:
        helper = r + ('_par' if r == 'Rdot' else '_omp')
        s += f'bool {helper}({sig}, {result} &result);\n{result} {r}_reference_cpu({sig});\n'
        s += f'{result} {r}({sig}) {{\n    {result} result;\n'
        s += f'    if (MPLAPACK_CUDA_ENTRY({r})({args}, result) || {helper}({args}, result)) return result;\n'
        s += f'    return {r}_reference_cpu({args});\n}}\n'
    path = TOP / f'mpblas/optimized/common/blas_cuda/{r}.cpp'
    if not path.exists() or path.read_text() != s:
        path.write_text(s)
