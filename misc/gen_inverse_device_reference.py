#!/usr/bin/env python3
"""Generate inverse device leaves/dependencies from unchanged FABLE sources.

Run from the repository root. Arithmetic text is not maintained by hand.
Complex Level-3 BLAS reuse the existing blas_dev templates.
"""
import re
from pathlib import Path

TOP = Path(__file__).resolve().parent.parent
OUT = TOP / 'mplapack/optimized/common/inverse_dev'
BLAS = ['Rdot', 'Cdotc', 'Rscal', 'Rtrmv', 'Ctrmv', 'Rgemv',
        'Rtrmm', 'Rtrsm', 'Rgemm', 'Rsyrk']
LAPACK = ['Clacgv', 'Rtrti2', 'Ctrti2', 'Rlauu2', 'Clauu2']
EXISTING = ['Cscal', 'CRscal', 'Cgemv', 'Ctrmm', 'Ctrsm', 'Cgemm']

def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    includes = []
    for name in BLAS + LAPACK:
        path = TOP / ('mpblas' if name in BLAS else 'mplapack') / 'reference' / (name + '.cpp')
        text = path.read_text()
        match = re.search(r'^(void|REAL|COMPLEX)\s+' + name + r'\((.*?)\) \{\n', text, re.M)
        if not match:
            raise SystemExit(f'{path}: function not found')
        end = text.index('\n}\n', match.end())
        body = text[match.start():end+3]
        body = re.sub(r'\bINTEGER\b', 'mplapackint', body)
        body = re.sub(r'\bMlsame\(', 'lsame(', body)
        body = re.sub(r'\bMxerbla\(', 'xerbla(', body)
        # Fortran integer MOD is C++ remainder here (nonnegative BLAS sizes).
        # Do not call the host-only fable intrinsic from a device function.
        body = re.sub(r'\bmod\(([^,()]+),([^()]+)\)', r'(\1 % \2)', body)
        if re.search(r'\bmod\(', body):
            raise SystemExit(f'{path}: unsupported MOD expression')
        for dep in BLAS + LAPACK + EXISTING:
            body = re.sub(r'\b' + dep + r'\(', dep + '_dev<REAL, COMPLEX>(', body)
        # The definition, unlike its calls, has its template arguments in front.
        body = body.replace(name + '_dev<REAL, COMPLEX>(', name + '_dev(', 1)
        if name == 'Rsyrk':
            body = body.replace('mplapackint const ldc)', 'mplapackint const ldc, mplapackint j0, mplapackint j1)')
            body = body.replace('for (j = 1; j <= n; j = j + 1)', 'for (j = j0 + 1; j <= j1; j = j + 1)')
        generated = ('// Generated by misc/gen_inverse_device_reference.py from\n'
                     f'// {path.relative_to(TOP)}; do not edit.\n'
                     'namespace mplapack_blas_dev {\n'
                     'template<class REAL, class COMPLEX> MPLAPACK_DEV_HD ' + body +
                     '} // namespace mplapack_blas_dev\n')
        write_if_changed(OUT / (name + '_dev.h'), generated)
        includes.append(f'#include "{name}_dev.h"\n')
    write_if_changed(OUT / 'inverse_dev.h',
        '// Generated by misc/gen_inverse_device_reference.py; do not edit.\n'
        '#ifndef MPLAPACK_INVERSE_DEV_H\n#define MPLAPACK_INVERSE_DEV_H\n'
        '#include "../../../../mpblas/optimized/common/blas_dev/blas_dev.h"\n' +
        ''.join(includes) + '#endif\n')
    print(f'wrote {len(includes)} inverse device templates in {OUT.relative_to(TOP)}')

if __name__ == '__main__':
    main()
