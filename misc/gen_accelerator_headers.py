#!/usr/bin/env python3
"""Generate include/mpblas_<backend>_<accelerator>.h.

Each header declares the accelerator entry points of one accelerator
library, libmplapack_<backend>_opt_<accelerator> (AGENTS.md, "Accelerator
entry points"):

    bool <Routine>_<backend>_<accelerator>(<arguments of <Routine>>);

The arguments are copied from the declaration of <Routine> in
include/mpblas_<backend>.h or include/mplapack_<backend>.h.  Run from the top source directory after
changing the routines an accelerator library computes:

    misc/gen_accelerator_headers.py
"""

import re
import sys
from pathlib import Path

TOP = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(TOP / "misc"))
from gen_backend_makefiles import BLAS_CUDA_SOURCES, CBLAS_CUDA_SOURCES  # noqa: E402

# Routines of mpblas/optimized/common/blas_cuda (dd, td, qd and, for the
# complex ones, MPFR), without the bridge sources.
BLAS_CUDA = [r for r in BLAS_CUDA_SOURCES if not r.endswith("_bridge_cuda")]
CBLAS_CUDA = [r for r in CBLAS_CUDA_SOURCES if not r.endswith("_bridge_cuda")]
# Real routines of mpblas/optimized/mpfr/cuda (blas3_bridge_cuda.cpp).
MPFR_CUDA = ["Rsyrk", "Rsyr2k", "Rsymm", "Rtrmm", "Rtrsm", "Rgemv", "Rsymv", "Rtrmv", "Rger",
             "Rsyr", "Rsyr2", "Rscal", "Rswap", "Rrot"]

LIBRARIES = [
    ("dd", "cuda", "ENABLE_CUDA", ["Rgemm", "Rpotrf", "Cpotrf", "Rgetrf", "Cgetrf"] + BLAS_CUDA + CBLAS_CUDA),
    ("td", "cuda", "ENABLE_TD_CUDA", ["Rgemm", "Rpotrf", "Cpotrf", "Rgetrf", "Cgetrf"] + BLAS_CUDA + CBLAS_CUDA),
    ("qd", "cuda", "ENABLE_QD_CUDA", ["Rgemm", "Rpotrf", "Cpotrf", "Rgetrf", "Cgetrf"] + BLAS_CUDA + CBLAS_CUDA),
    ("mpfr", "cuda", "ENABLE_MPFR_CUDA", ["Rgemm", "Rpotrf", "Rgetrf"] + MPFR_CUDA + CBLAS_CUDA),
    ("binary128", "opencl", "ENABLE_OPENCL_BINARY128", ["Rgemm"]),
]


def license_text():
    text = (TOP / "include" / "mpblas_dd.h").read_text()
    return text[:text.index("*/") + 2]


def declarations(backend):
    decls = {}
    for header in ("mpblas", "mplapack"):
        for line in (TOP / "include" / ("%s_%s.h" % (header, backend))).read_text().splitlines():
            m = re.match(r"void ([RC][A-Za-z0-9]+)\((.*)\);\s*$", line)
            if m:
                decls[m.group(1)] = m.group(2)
    return decls


def main():
    lic = license_text()
    for backend, accel, conditional, routines in LIBRARIES:
        decls = declarations(backend)
        guard = "_MPBLAS_%s_%s_H_" % (backend.upper(), accel.upper())
        lines = [lic, "",
                 "// Generated by misc/gen_accelerator_headers.py; do not edit.",
                 "//",
                 "// Accelerator entry points of libmplapack_%s_opt_%s (AGENTS.md," % (backend, accel),
                 "// \"Accelerator entry points\"): <Routine>_%s_%s takes the arguments of" % (backend, accel),
                 "// <Routine> and returns true when the %s device computed the result," % accel,
                 "// false (every output untouched) when it did not: invalid arguments,",
                 "// quick returns, calls that are not eligible, device errors.  It never",
                 "// computes on the CPU.  The environment variables of the library apply.",
                 "",
                 "#ifndef %s" % guard,
                 "#define %s" % guard,
                 "",
                 "#include <mpblas_%s.h>" % backend,
                 ""]
        for r in routines:
            if r not in decls:
                sys.exit("%s is not declared in the BLAS/LAPACK headers for %s" % (r, backend))
            lines.append("bool %s_%s_%s(%s);" % (r, backend, accel, decls[r]))
        lines += ["", "#endif", ""]
        out = TOP / "include" / ("mpblas_%s_%s.h" % (backend, accel))
        out.write_text("\n".join(lines))
        print("wrote %s (%d entry points; Makefile.am conditional %s)" % (out.relative_to(TOP), len(routines), conditional))


if __name__ == "__main__":
    main()
