#!/usr/bin/env python3
"""
Strip LAPACK header blocks from C++ / header files generated by cout.py.

We remove exactly one contiguous comment block per file:

- Start of the block:
    * the first comment line whose text contains "\\brief"
      (for newer LAPACK with doxygen markup), OR
    * the first comment line whose text contains "-- LAPACK"
      (auxiliary/computational/driver routine), OR
    * the first comment line whose text contains one of
        "Scalar Arguments", "Array Arguments", "Parameters".

- End of the block:
    * the first comment line whose text contains "Executable Statements"
      (case-insensitive).

Everything between these two markers (inclusive) is removed.
All other comments, including "Quick return" and algorithmic notes
inside the body of the routine, are preserved.
"""

import sys
from pathlib import Path


def is_comment_line(line: str) -> bool:
    """Return True if the line is a C++ comment starting with '//'."""
    return line.lstrip().startswith("//")


def extract_comment_text(line: str):
    """
    Extract logical comment content from a cout.py-generated line.

    Examples:
        //C*> \brief foo
            -> "*> \brief foo"

        //C     .. Executable Statements ..
            -> ".. Executable Statements .."

        // something else
            -> "something else"
    """
    stripped = line.lstrip()
    if not stripped.startswith("//"):
        return None

    # Drop leading //
    text = stripped[2:].lstrip()

    # cout.py marks Fortran comments as //C...
    if text.startswith("C"):
        if len(text) == 1 or text[1].isspace():
            text = text[1:].lstrip()

    return text.rstrip("\r\n")


def should_start_header_block(text: str) -> bool:
    """
    Decide whether this comment text should start the LAPACK header block.
    """
    if text is None:
        return False

    t = text
    lower = t.lower()

    # Newer LAPACK: doxygen-style brief.
    if "\\brief" in t:
        return True

    # Classic LAPACK header markers.
    if "-- lapack" in lower:
        return True

    # Section headings that only make sense in the top-of-file header.
    header_keys = [
        "scalar arguments",
        "array arguments",
        "parameters",
    ]
    for key in header_keys:
        if key in lower:
            return True

    return False


def is_header_end(text: str) -> bool:
    """Return True if this comment text marks the end of the header block."""
    if text is None:
        return False
    return "executable statements" in text.strip().lower()


def strip_lapack_header_block(path: Path) -> None:
    """Remove the LAPACK header block from a single file, if present."""
    try:
        src = path.read_text(encoding="utf-8", errors="ignore")
    except OSError as e:
        print(f"strip_lapack_header: failed to read {path}: {e}", file=sys.stderr)
        return

    lines = src.splitlines(keepends=True)

    out_lines = []
    in_skip_block = False
    header_removed = False

    for line in lines:
        if not in_skip_block:
            if not header_removed and is_comment_line(line):
                text = extract_comment_text(line) or ""
                if should_start_header_block(text):
                    # Start skipping from this line
                    in_skip_block = True
                    header_removed = True
                    continue  # do not output this line
            # Not the start of header: keep as-is
            out_lines.append(line)
        else:
            # Currently skipping header comments
            if is_comment_line(line):
                text = extract_comment_text(line) or ""
                if is_header_end(text):
                    # End marker: stop skipping after this line
                    in_skip_block = False
                    continue  # do not output this line
                # Still inside header block: keep skipping
                continue
            else:
                # Safety valve: header block should be entirely comments.
                # If we see a non-comment line, stop skipping and keep it.
                in_skip_block = False
                out_lines.append(line)

    try:
        path.write_text("".join(out_lines), encoding="utf-8")
    except OSError as e:
        print(f"strip_lapack_header: failed to write {path}: {e}", file=sys.stderr)


def main(argv):
    if len(argv) < 2:
        print("Usage: strip_boilerplate_comments.py FILE [FILE...]", file=sys.stderr)
        sys.exit(1)

    for arg in argv[1:]:
        p = Path(arg)
        if not p.is_file():
            print(f"strip_lapack_header: {p} is not a file, skipping", file=sys.stderr)
            continue
        strip_lapack_header_block(p)


if __name__ == "__main__":
    main(sys.argv)
